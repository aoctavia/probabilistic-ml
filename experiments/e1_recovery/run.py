"""E1 — Recovery under known truth.

Sweeps over N, D, K, and tau. For each configuration, simulates data from
the M0 model, runs CAVI, and records:
  - subspace_distance (Z_true vs M_Z posterior mean)
  - matched_correlation (Z_true vs M_Z posterior mean)
  - E[tau] vs true tau
  - ELBO at convergence, n_iter, converged flag

Results are written to results/results.json.
Figures are generated by plot.py.

Usage:
    python experiments/e1_recovery/run.py experiments/e1_recovery/config.yaml
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import jax
import yaml

from sfm.diagnostics.alignment import matched_correlation, subspace_distance
from sfm.inference.cavi import run_cavi
from sfm.models.m0_baseline import M0Hyperparams
from sfm.simulate import simulate_m0


def run_single(
    N: int,
    D: int,
    K: int,
    tau: float,
    seed: int,
    cavi_max_iter: int,
    cavi_tol: float,
) -> dict:  # type: ignore[type-arg]
    """Run one sweep point and return a result dict."""
    key_data = jax.random.PRNGKey(seed)
    key_cavi = jax.random.PRNGKey(seed + 10_000)

    data = simulate_m0(key_data, N=N, D=D, K=K, tau=tau)
    hp = M0Hyperparams()

    t0 = time.perf_counter()
    result = run_cavi(
        data.X, K=K, hp=hp, key=key_cavi,
        max_iter=cavi_max_iter, tol=cavi_tol,
    )
    wall_sec = time.perf_counter() - t0

    sd = subspace_distance(data.Z_true, result.state.M_Z)
    mc = matched_correlation(data.Z_true, result.state.M_Z)
    e_tau = result.state.a_N / result.state.b_N

    return {
        "N": N, "D": D, "K": K, "tau": tau, "seed": seed,
        "subspace_distance": sd,
        "matched_correlation": mc,
        "e_tau": float(e_tau),
        "true_tau": tau,
        "tau_ratio": float(e_tau) / tau,
        "elbo_final": result.elbo_history[-1],
        "n_iter": result.n_iter,
        "converged": result.converged,
        "wall_sec": wall_sec,
    }


def main(config_path: Path) -> None:
    with open(config_path) as f:
        cfg = yaml.safe_load(f)

    seed_base = cfg["seed"]
    defaults = cfg["defaults"]
    sweep = cfg["sweep"]
    max_iter = cfg.get("cavi_max_iter", 500)
    tol = float(cfg.get("cavi_tol", 1e-4))

    results = []
    sweep_count = 0

    # Sweep each dimension individually, fixing all others to defaults
    for dim, values in sweep.items():
        for val in values:
            kwargs = dict(defaults)
            kwargs[dim] = val
            kwargs["seed"] = seed_base + sweep_count

            print(
                f"  N={kwargs['N']:4d}  D={kwargs['D']:4d}  "
                f"K={kwargs['K']:2d}  tau={kwargs['tau']:.1f}  "
                f"(sweep {dim}={val})",
                end="  ", flush=True,
            )

            rec = run_single(
                N=int(kwargs["N"]), D=int(kwargs["D"]),
                K=int(kwargs["K"]), tau=float(kwargs["tau"]),
                seed=int(kwargs["seed"]),
                cavi_max_iter=max_iter, cavi_tol=tol,
            )
            rec["sweep_dim"] = dim
            rec["sweep_val"] = val
            results.append(rec)
            sweep_count += 1

            print(
                f"subspace_dist={rec['subspace_distance']:.3f}  "
                f"corr={rec['matched_correlation']:.3f}  "
                f"iters={rec['n_iter']}  "
                f"{'OK' if rec['converged'] else 'MAX'}",
            )

    out_dir = config_path.parent / "results"
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "results.json"
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2)

    print(f"\nSaved {len(results)} results to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(f"Usage: python {sys.argv[0]} <config.yaml>")
        sys.exit(1)
    main(Path(sys.argv[1]))
